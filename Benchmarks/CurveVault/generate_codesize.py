#!/usr/bin/env python3
"""Contract-local adapter for the pinned Vyper codesize dispatcher.

All proof bodies below are dispatcher plumbing generated from the bytecode table;
the contract bodies and constructor remain the standard proof_skeleton stubs.
Spec.lean is kept because it contains the audited ABI/storage configuration.
"""
from pathlib import Path
import json
import re
import sys

directory = Path(__file__).resolve().parent
repo = directory.parents[1]
sys.path.insert(0, str(repo / "scripts"))
import proof_skeleton as p

c = p.load_contract(directory, "Benchmarks.CurveVault", None, None, "Vault")
c.wf = "storageWF"
code = c.runtime
assert code[:18].hex() == "5f3560e01c60056005600583060261206001"
signatures = {int.from_bytes(t.selector, "big"): t.signature for t in c.transitions}
rows = []
for bucket in range(5):
    header = int.from_bytes(code[8288 + 5*bucket:8293 + 5*bucket], "big")
    magic, table, size = header >> 24, (header >> 8) & 65535, header & 255
    for index in range(size):
        record = int.from_bytes(code[table + 7*index:table + 7*index + 7], "big")
        selector, entry, flags = record >> 24, (record >> 8) & 65535, record & 255
        assert selector % 5 == bucket
        assert ((magic * selector) >> 24) % size == index
        assert code[entry] == 0x5b
        rows.append(dict(signature=signatures[selector], selector=f"0x{selector:08x}",
            bucket=bucket, magic=magic, index=index, table=table, tableSize=size,
            entry=entry, minCalldata=flags & 254, nonpayable=bool(flags & 1)))
(directory / "dispatcher.json").write_text(json.dumps(rows, indent=2) + "\n")
by_sel = {int(r["selector"], 16): r for r in rows}
assert set(by_sel) == {int.from_bytes(t.selector, "big") for t in c.transitions}

common = p.render_common_vyper(c)
common = re.sub(r'/-- The storage precondition.*?-/', '''/-- Initial address words in slots 0..4 are canonical, so the address getters
return their full raw words. No string-length, mapping noncollision, or post-call
storage assumption is made. The controller's raw word is retained separately
when it is re-read and passed to transferFrom; see HANDOFF.md. -/''', common, flags=re.S)
# Reduce only the signature projection. Unfolding the entire large contract under
# simp for each bridge needlessly traverses every unrelated function body.
for t in c.transitions:
    types = ', '.join(p.abi_type_term(x) for x in t.signature.split('(', 1)[1][:-1].split(',') if x)
    source_name = t.signature.split('(', 1)[0]
    pattern = (r'(  have hsig : transitionSigStr ' + re.escape(t.handle) +
        r' = "[^"\n]+" := by\n).*?(?=  unfold selectorOf)')
    replacement = (r'\1' + f'    change ABI.printSignature ⟨"{source_name}", [{types}]⟩ = _\n'
        '    simp [ABI.printSignature, ABI.abiToSigStr, ABI.elemToSigStr, ABI.intTypeToSigStr,\n'
        '      show Nat.repr 256 = "256" by decide +kernel, show Nat.repr 8 = "8" by decide +kernel]\n'
        '    <;> decide +kernel\n')
    common, count = re.subn(pattern, replacement, common, flags=re.S)
    assert count == 1, t.signature
common = common.replace("def storageWF : StorageWF := fun _ _ => True", '''def storageWF : StorageWF := fun σ I =>
  ∀ slot : Nat, slot < 5 →
    (((σ.get? I.codeOwner).getD default).storage.getD
      (UInt256.ofNat slot) (UInt256.ofNat 0)).toNat < 2 ^ 160''')
p.write_file(directory / "Common.lean", common, True)

out = ['''import Benchmarks.CurveVault.Common
import Benchmarks.CurveVault.RuntimeBlocks_001
import Benchmarks.CurveVault.RuntimeBlocks_024

/-! Generated by `generate_codesize.py` from the pinned two-stage dispatch table.
The selected entry's calldata/payability guard starts at pc 73; it jumps to the
function entry encoded in bits 8..23 of the selected seven-byte record. -/

open Solm ABI Ethereum Ethereum.EVM Reasoning.Theory Reasoning.Reach Reasoning.VyperDispatch
namespace Benchmarks.CurveVault
set_option maxRecDepth 2000
set_option maxHeartbeats 0

def vaultFirstMemory (s : UInt256) : ByteArray :=
  vaultBytecode.write ((UInt256.ofNat 8288) +
    UInt256.mul (UInt256.mod s (UInt256.ofNat 5)) (UInt256.ofNat 5)).toNat ByteArray.empty 27 5

def vaultHeader (s : UInt256) : UInt256 := memLoad ⟨0⟩ (vaultFirstMemory s)

def vaultDispatchMemory (s : UInt256) : ByteArray :=
  vaultBytecode.write
    (UInt256.land (UInt256.ofNat 65535) (UInt256.shiftRight (vaultHeader s) (UInt256.ofNat 8)) +
      UInt256.mul (UInt256.mod
        (UInt256.shiftRight (UInt256.mul (UInt256.shiftRight (vaultHeader s) (UInt256.ofNat 24)) s)
          (UInt256.ofNat 24))
        (UInt256.land (UInt256.ofNat 255) (vaultHeader s))) (UInt256.ofNat 7)).toNat
    (vaultFirstMemory s) 25 7

def vaultDispatchEntry (s : UInt256) : UInt256 := memLoad ⟨0⟩ (vaultDispatchMemory s)

theorem vaultSizeGt {I : ExecutionEnv} (hsz : 4 ≤ I.calldata.size)
    (hsize : I.calldata.size < UInt256.size) :
    UInt256.gt (UInt256.ofNat I.calldata.size) (UInt256.ofNat 3) = ⟨1⟩ := by
  apply ugt_one
  rw [ulit_toNat' _ hsize]
  change 3 < I.calldata.size
  omega

/-- The selected record has been loaded; the entry-specific guard is next. -/
theorem vaultReachGuard {σ σ₀ A I} {g : Sat256}
    (hcode : I.code = vaultBytecode) (hsz : 4 ≤ I.calldata.size)
    (hsize : I.calldata.size < UInt256.size)
    (hentry : UInt256.shiftRight (vaultDispatchEntry (solcSelectorWord I)) ⟨24⟩ = solcSelectorWord I) :
    ∃ k C, RD vaultBytecode I g (initState σ σ₀ g A I) (UInt256.ofNat 73)
      [vaultDispatchEntry (solcSelectorWord I), solcSelectorWord I]
      (vaultDispatchMemory (solcSelectorWord I)) (UInt256.ofNat 1) ByteArray.empty σ k C := by
  have rd0 := RD.initState (g := g) (σ := σ) (σ₀ := σ₀) (A := A) hcode
  have rd1 := vaultBlocks.vault_block_0_fallthrough (R := []) (mem := ByteArray.empty)
    (aw := UInt256.ofNat 0) (by simp) (by
      change UInt256.isZero (UInt256.land
        (UInt256.gt (UInt256.ofNat I.calldata.size) (UInt256.ofNat 3))
        (UInt256.eq (UInt256.shiftRight (vaultDispatchEntry (solcSelectorWord I)) ⟨24⟩)
          (solcSelectorWord I))) = UInt256.ofNat 0
      rw [hentry, u256_eq_refl, vaultSizeGt hsz hsize]
      decide) rd0
  exact ⟨_, _, rd1⟩

theorem vaultRevertMismatch {σ σ₀ A I} {g : Sat256}
    (hcode : I.code = vaultBytecode)
    (hcond : UInt256.isZero (UInt256.land
      (UInt256.gt (UInt256.ofNat I.calldata.size) (UInt256.ofNat 3))
      (UInt256.eq (UInt256.shiftRight (vaultDispatchEntry (solcSelectorWord I)) ⟨24⟩)
        (solcSelectorWord I))) ≠ UInt256.ofNat 0) :
    RDrev vaultBytecode g (initState σ σ₀ g A I) := by
  have rd0 := RD.initState (g := g) (σ := σ) (σ₀ := σ₀) (A := A) hcode
  have rd1 := vaultBlocks.vault_block_0_taken (R := []) (mem := ByteArray.empty)
    (aw := UInt256.ofNat 0) (by simp) hcond (by native_decide) rd0
  exact vaultBlocks.vault_block_6768 (by simp [vaultBlocks.vault_block_0_taken_stack]) rd1
''']
out += p.solm_dispatch_facts(c, False, True)

for t in c.transitions:
    value = int.from_bytes(t.selector, 'big')
    r = by_sel[value]
    leaf = (value << 24) | (r['entry'] << 8) | r['minCalldata'] | int(r['nonpayable'])
    out += [f'''/-- `{t.signature}`: bucket {r['bucket']}, index {r['index']}, body pc {r['entry']}. -/
theorem vaultReach{t.cap}Body {{σ σ₀ A I}} {{g : Sat256}}
    (hcode : I.code = vaultBytecode) (hsz : 4 ≤ I.calldata.size)
    (hsize : I.calldata.size < UInt256.size) (hsel : selIs I (vaultSelBytes {t.index})) :
    ∃ k C, RD vaultBytecode I g (initState σ σ₀ g A I) (UInt256.ofNat 73)
      [⟨{leaf}⟩, solcSelectorWord I]
      (vaultDispatchMemory ⟨{value}⟩) (UInt256.ofNat 1) ByteArray.empty σ k C := by''']
    out += p.ProofGen(c, p.Dispatcher(c, None)).hword_lines(t)
    out += [f'''  have hentry : vaultDispatchEntry ⟨{value}⟩ = ⟨{leaf}⟩ := by native_decide
  have hmatch : UInt256.shiftRight (vaultDispatchEntry (solcSelectorWord I)) ⟨24⟩ = solcSelectorWord I := by
    rw [hword, hentry]
    native_decide
  obtain ⟨k, C, h⟩ := vaultReachGuard (σ := σ) (σ₀ := σ₀) (A := A) (g := g) hcode hsz hsize hmatch
  exact ⟨k, C, by simpa only [hword, hentry] using h⟩
''']

values = ', '.join('⟨' + str(int.from_bytes(t.selector, 'big')) + '⟩' for t in c.transitions)
out += [f'''def vaultSelectorWords : List UInt256 := [{values}]

/-- Every record read by the two-stage lookup contains one of the 46 ABI selectors. -/
theorem vaultLookupMember (s : UInt256) :
    UInt256.shiftRight (vaultDispatchEntry s) ⟨24⟩ ∈ vaultSelectorWords := by
  have hlt : s.toNat % 5 < 5 := Nat.mod_lt _ (by decide)
  generalize hm : s.toNat % 5 = m at hlt
  interval_cases m''']
for bucket in range(5):
    r = next(r for r in rows if r['bucket'] == bucket)
    n, magic, table = r['tableSize'], r['magic'], r['table']
    header = int.from_bytes(code[8288 + 5*bucket:8293 + 5*bucket], 'big')
    out += [f'''  · have hmod := mod_eq_ofNat (sel := s) (n := 5) (by decide) (by decide) hm
    have hmem : vaultFirstMemory s = vaultFirstMemory (UInt256.ofNat {bucket}) := by
      unfold vaultFirstMemory
      rw [hmod]
      rfl
    have hh : vaultHeader s = UInt256.ofNat {header} := by
      unfold vaultHeader
      rw [hmem]
      native_decide
    have ha : UInt256.shiftRight (vaultHeader s) (UInt256.ofNat 24) = UInt256.ofNat {magic} := by
      rw [hh]; native_decide
    have hb : UInt256.land (UInt256.ofNat 65535) (UInt256.shiftRight (vaultHeader s) (UInt256.ofNat 8)) = UInt256.ofNat {table} := by
      rw [hh]; native_decide
    have hc : UInt256.land (UInt256.ofNat 255) (vaultHeader s) = UInt256.ofNat {n} := by
      rw [hh]; native_decide
    let q := UInt256.shiftRight (UInt256.mul (UInt256.ofNat {magic}) s) (UInt256.ofNat 24)
    have hjlt : q.toNat % {n} < {n} := Nat.mod_lt _ (by decide)
    generalize hj : q.toNat % {n} = j at hjlt
    have hjmod := mod_eq_ofNat (sel := q) (n := {n}) (by decide) (by decide) hj
    unfold vaultDispatchEntry vaultDispatchMemory
    rw [ha, hb, hc, hmem, show UInt256.mod q (UInt256.ofNat {n}) = UInt256.ofNat j from hjmod]
    interval_cases j <;> native_decide''']

out += ['''
theorem vaultX_short {σ σ₀ A I} {g : Sat256}
    (hcode : I.code = vaultBytecode) (hshort : I.calldata.size < 4) :
    RDrev vaultBytecode g (initState σ σ₀ g A I) := by
  apply vaultRevertMismatch hcode
  have hs : UInt256.gt (UInt256.ofNat I.calldata.size) (UInt256.ofNat 3) = ⟨0⟩ := by
    apply ugt_zero
    rw [ulit_toNat' _ (by exact lt_trans hshort (by decide))]
    change I.calldata.size ≤ 3
    omega
  rw [hs, u256_land_zero_left]
  decide

theorem vaultX_noMatch {σ σ₀ A I} {g : Sat256}
    (hcode : I.code = vaultBytecode) (hsz : 4 ≤ I.calldata.size)
    (hsize : I.calldata.size < UInt256.size)
    (hnm : ∀ i, i < 46 → (vaultSelBytes i == I.calldata.extract 0 4) = false) :
    RDrev vaultBytecode g (initState σ σ₀ g A I) := by
  have hn : UInt256.shiftRight (vaultDispatchEntry (solcSelectorWord I)) ⟨24⟩ ≠ solcSelectorWord I := by
    intro he
    have hm := vaultLookupMember (solcSelectorWord I)
    rw [he] at hm
    simp only [vaultSelectorWords, List.mem_cons, List.not_mem_nil, or_false] at hm
    rcases hm with ''' + ' | '.join('h' + str(t.index) for t in c.transitions)]
for t in c.transitions:
    value = int.from_bytes(t.selector, 'big')
    out += [f'''    · have hz := {t.name}EvmSelector hsz
      have heq : UInt256.eq ⟨{value}⟩ (solcSelectorWord I) = ⟨1⟩ := by
        rw [h{t.index}]; native_decide
      rw [hz, hnm {t.index} (by decide)] at heq
      cases heq''']
out += ['''  apply vaultRevertMismatch hcode
  rw [u256_eq_of_ne hn, u256_land_zero_right]
  decide

end Benchmarks.CurveVault
''']
p.write_file(directory / "Dispatch.lean", '\n'.join(out), True)
for t in c.transitions:
    r = by_sel[int.from_bytes(t.selector, 'big')]
    p.write_file(directory / (t.cap + '.lean'), p.render_function_vyper(c, t, (r['bucket'], 73)), True)
p.write_file(directory / 'Constructor.lean', p.render_constructor(c), True)
p.write_file(directory / 'Correct.lean', p.render_correct_vyper(c), True)
